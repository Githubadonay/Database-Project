-- For each city (in alphabetic order) compute the number of games.
SELECT CITY_AT, 
COUNT(*) 
FROM SCHEDULED_GAME_AT
GROUP BY CITY_AT
ORDER BY CITY_AT ASC;
-- For each club (in alphabetic order) compute the total number of coaches hired.
SELECT
  CLUB_AT.NAME_AT,
  COUNT(DISTINCT TEAM_AT.COACH_AT_ID_AT) AS 'HIRED COACHES'
FROM CLUB_AT
JOIN TEAM_AT ON TEAM_AT.CLUB_AT_ID_AT = CLUB_AT.ID_AT
GROUP BY CLUB_AT.NAME_AT
ORDER BY CLUB_AT.NAME_AT ASC;

-- For each division in the current season compute the total number of clubs.
SELECT DIVISION_AT.ID_AT, DIVISION_AT.AGE_AT, DIVISION_AT.SEX_AT, DIVISION_AT.RANK_AT,
  COUNT(DISTINCT TEAM_AT.CLUB_AT_ID_AT) AS 'CLUB COUNT'
FROM DIVISION_AT 
JOIN REGISTERED_AT ON REGISTERED_AT.DIVISION_AT_ID_AT = DIVISION_AT.ID_AT
JOIN TEAM_AT ON TEAM_AT.ID_AT = REGISTERED_AT.TEAM_AT_ID_AT
GROUP BY DIVISION_AT.ID_AT, DIVISION_AT.AGE_AT, DIVISION_AT.SEX_AT, DIVISION_AT.RANK_AT;

-- For each coach (in alphabetic order) compute the total numbers of players.
SELECT COACH_AT.FIRST_NAME_AT,COACH_AT.LAST_NAME_AT,
  COUNT(PLAYER_AT.ID_AT) AS TOTAL
FROM COACH_AT
LEFT JOIN TEAM_AT ON TEAM_AT.COACH_AT_ID_AT = COACH_AT.ID_AT
LEFT JOIN PLAYER_AT ON PLAYER_AT.TEAM_AT_ID_AT = TEAM_AT.ID_AT
GROUP BY COACH_AT.FIRST_NAME_AT,COACH_AT.LAST_NAME_AT
ORDER BY COACH_AT.FIRST_NAME_AT ASC;



