-- Task 3 - Create table by Adonay Tesfamichael
CREATE TABLE SEASON_AT(
ID_AT INT PRIMARY KEY AUTO_INCREMENT,
SEASON_NAME_AT ENUM('FALL', 'SPRING', 'WINTER', 'SUMMER') NOT NULL, 
YEAR_AT INT NOT NULL,
REGISTRATION_START_DATA_AT DATE NOT NULL,
REGISTRATION_END_DATA_AT DATE NOT NULL,
SEASON_START_DATE_AT DATE NOT NULL,
SEASON_END_DATE_AT DATE NOT NULL
);
DESCRIBE SEASON_AT;

CREATE TABLE DIVISION_AT(
ID_AT INT PRIMARY KEY AUTO_INCREMENT,
AGE_AT VARCHAR(3) NOT NULL,
SEX_AT ENUM('Boys', 'Girls') NOT NULL,
RANK_AT ENUM('1', '2') NOT NULL,
EMAIL_AT VARCHAR(35) NOT NULL UNIQUE,
PHONE_AT CHAR(13) NOT NULL UNIQUE,
SEASON_AT_ID_AT INT NOT NULL,
FOREIGN KEY (SEASON_AT_ID_AT) REFERENCES SEASON_AT(ID_AT)
);
DESCRIBE DIVISION_AT;

CREATE TABLE CLUB_AT(
ID_AT INT PRIMARY KEY AUTO_INCREMENT,
NAME_AT VARCHAR(24) NOT NULL,
EMAIL_AT VARCHAR(35) NOT NULL,
ABBREVIATION_AT VARCHAR(5) NOT NULL,
PHONE_AT CHAR(13) NOT NULL
);
DESCRIBE CLUB_AT;

CREATE TABLE COACH_AT(
ID_AT INT PRIMARY KEY AUTO_INCREMENT,
FIRST_NAME_AT VARCHAR(15) NOT NULL,
LAST_NAME_AT VARCHAR(15) NOT NULL,
DOB_AT DATE NOT NULL,
YEAR_STARTED_AT DECIMAL(4,0) NOT NULL,
PHONE_AT CHAR(12) NOT NULL
);
DESCRIBE COACH_AT;

CREATE TABLE TEAM_AT(
ID_AT INT PRIMARY KEY AUTO_INCREMENT,
BIRTH_YEAR_AT INT NOT NULL,
SEX_AT ENUM('Boys', 'Girls') NOT NULL, 
NAME_AT VARCHAR(20) NOT NULL,
EMAIL_AT VARCHAR(35) NOT NULL,
PHONE_AT CHAR(13) NOT NULL,
CLUB_AT_ID_AT INT NOT NULL,
COACH_AT_ID_AT INT NOT NULL,
FOREIGN KEY (CLUB_AT_ID_AT) REFERENCES CLUB_AT(ID_AT),
FOREIGN KEY (COACH_AT_ID_AT) REFERENCES COACH_AT(ID_AT)
);
DESCRIBE TEAM_AT;

CREATE TABLE PLAYER_AT(
ID_AT INT PRIMARY KEY AUTO_INCREMENT,
FIRST_NAME_AT VARCHAR(15) NOT NULL,
LAST_NAME_AT VARCHAR(15) NOT NULL,
DOB_AT DATE NOT NULL,
JERSEY_NUMBER_AT INT NOT NULL,
PARENT_EMAIL_AT VARCHAR(20) NOT NULL,
TEAM_AT_ID_AT INT NOT NULL,
FOREIGN KEY (TEAM_AT_ID_AT) REFERENCES TEAM_AT(ID_AT)
);
DESCRIBE PLAYER_AT;

CREATE TABLE REGISTERED_AT(
ID_AT INT PRIMARY KEY AUTO_INCREMENT,
REG_DATE_AT DATE NOT NULL,
TEAM_AT_ID_AT INT NOT NULL,
DIVISION_AT_ID_AT INT NOT NULL,
FOREIGN KEY (TEAM_AT_ID_AT) REFERENCES TEAM_AT(ID_AT),
FOREIGN KEY (DIVISION_AT_ID_AT) REFERENCES DIVISION_AT(ID_AT)
);
DESCRIBE REGISTERED_AT;



