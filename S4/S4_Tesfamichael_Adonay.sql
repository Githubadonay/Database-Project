-- Count all the players registered for a team in FALL 2020.
SELECT COUNT(PLAYER_AT.ID_AT) AS '2020 PLAYERS'
FROM PLAYER_AT 
JOIN TEAM_AT ON PLAYER_AT.TEAM_AT_ID_AT = TEAM_AT.ID_AT
JOIN REGISTERED_AT ON REGISTERED_AT.TEAM_AT_ID_AT = TEAM_AT.ID_AT
JOIN DIVISION_AT ON REGISTERED_AT.DIVISION_AT_ID_AT = DIVISION_AT.ID_AT
JOIN SEASON_AT ON DIVISION_AT.SEASON_AT_ID_AT = SEASON_AT.ID_AT
WHERE SEASON_AT.SEASON_NAME_AT = 'FALL' AND SEASON_AT.YEAR_AT = 2020;
-- Count all the coaches hired by a club in SPRING 2020.
SELECT COUNT(COACH_AT.ID_AT) AS '2020 COACH HIRED'
FROM COACH_AT 
JOIN TEAM_AT ON COACH_AT.ID_AT = TEAM_AT.COACH_AT_ID_AT
JOIN REGISTERED_AT ON TEAM_AT.ID_AT = REGISTERED_AT.TEAM_AT_ID_AT
JOIN DIVISION_AT ON REGISTERED_AT.DIVISION_AT_ID_AT = DIVISION_AT.ID_AT
JOIN SEASON_AT ON DIVISION_AT.SEASON_AT_ID_AT = SEASON_AT.ID_AT
WHERE SEASON_AT.SEASON_NAME_AT = 'SPRING' AND SEASON_AT.YEAR_AT = 2020;
-- List the player(s) that have the biggest jersey number (the full name in a column named player).
SELECT CONCAT(PLAYER_AT.FIRST_NAME_AT, ' ', PLAYER_AT.LAST_NAME_AT) AS player
FROM PLAYER_AT
WHERE PLAYER_AT.JERSEY_NUMBER_AT = ( 
SELECT MAX(JERSEY_NUMBER_AT)
FROM PLAYER_AT);
