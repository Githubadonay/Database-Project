-- Task 3 - Create tables ADONAY TESFAMICHAEL
CREATE TABLE TEACHER_AT(
ID_AT INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
FIRST_NAME_AT VARCHAR(15) NOT NULL,
MIDDLE_NAME_AT VARCHAR(15),
LAST_NAME_AT VARCHAR(15) NOT NULL,
HOME_PHONE_AT CHAR(13) NOT NULL,
WORK_EMAIL_AT VARCHAR(30) NOT NULL,
PERSONAL_EMAIL_AT VARCHAR(30),
COLLEGE_AT VARCHAR(50),
HIGHEST_DEGREE_AT VARCHAR(5) NOT NULL,
DEGREE_AREA_AT VARCHAR(25) NOT NULL
);
DESCRIBE TEACHER_AT;

CREATE TABLE CLASS_AT(
CODE_AT VARCHAR(2) PRIMARY KEY NOT NULL,
AGE_LEVEL_AT VARCHAR(7) NOT NULL,
COLOR_AT VARCHAR(5) NOT NULL,
ROOM_NUMBER_AT INT NOT NULL,
PHONE_NUMBER_AT CHAR(13) NOT NULL,
DIRECTION_AT VARCHAR(160),
CAPACITY_AT INT NOT NULL
);
DESCRIBE CLASS_AT;

CREATE TABLE ASSIGNMENT_AT(
CLASS_AT_CODE_AT VARCHAR(2) NOT NULL, 
TEACHER_AT_ID_AT INT NOT NULL,
FOREIGN KEY (CLASS_AT_CODE_AT) REFERENCES CLASS_AT(CODE_AT),
FOREIGN KEY (TEACHER_AT_ID_AT) REFERENCES TEACHER_AT(ID_AT)
);
DESCRIBE ASSIGNMENT_AT;

CREATE TABLE STUDENT_AT(
ID_AT INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
FIRST_NAME_AT VARCHAR(15) NOT NULL,
MIDDLE_NAME_AT VARCHAR(15),
LAST_NAME_AT VARCHAR(15) NOT NULL,
NICK_NAME_AT VARCHAR(10),
DATE_OF_BIRTH_AT DATE NOT NULL,
ADDRESS_AT VARCHAR(55) NOT NULL,
CITY_AT VARCHAR(15) NOT NULL,
ZIPCODE_AT DECIMAL(5,0) NOT NULL,
STREET_AT VARCHAR(35) NOT NULL,
CLASS_AT_CODE_AT VARCHAR(2) NOT NULL,
FOREIGN KEY (CLASS_AT_CODE_AT) REFERENCES CLASS_AT(CODE_AT)
);
DESCRIBE STUDENT_AT;

CREATE TABLE PARENT_AT(
ID_AT INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
FIRST_NAME_AT VARCHAR(15) NOT NULL,
MIDDLE_NAME_AT VARCHAR(15),
LAST_NAME_AT VARCHAR(15) NOT NULL,
HOME_PHONE_AT CHAR(13),
MOBILE_PHONE_AT CHAR(13) NOT NULL,
WORK_PHONE_AT CHAR(13),
EMAIL_AT VARCHAR(30),
RELATION VARCHAR(20) NOT NULL
);
DESCRIBE PARENT_AT;

CREATE TABLE RELATIONSHIP_AT(
STUDENT_AT_ID_AT INT NOT NULL,
PARENT_AT_ID_AT INT NOT NULL,
FOREIGN KEY (STUDENT_AT_ID_AT) REFERENCES STUDENT_AT(ID_AT),
FOREIGN KEY (PARENT_AT_ID_AT) REFERENCES PARENT_AT(ID_AT)
);
DESCRIBE RELATIONSHIP_AT;

CREATE TABLE LUNCH_ORDER_AT(
ID_AT INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
QUANTITY_AT INT NOT NULL,
DATE_AT DATE NOT NULL,
STUDENT_AT_ID_AT INT NOT NULL,
FOREIGN KEY (STUDENT_AT_ID_AT) REFERENCES STUDENT_AT(ID_AT)
);
DESCRIBE LUNCH_ORDER_AT;

CREATE TABLE LUNCH_ITEM_AT(
CODE_AT INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
ITEM_NAME_AT VARCHAR(26) NOT NULL,
CALORIES INT NOT NULL
);
DESCRIBE LUNCH_ITEM_AT;

CREATE TABLE ORDER_ITEM_AT(
LUNCH_ORDER_AT_ID_AT INT NOT NULL,
LUNCH_ITEM_AT_CODE_AT INT NOT NULL,
FOREIGN KEY (LUNCH_ORDER_AT_ID_AT) REFERENCES LUNCH_ORDER_AT(ID_AT),
FOREIGN KEY (LUNCH_ITEM_AT_CODE_AT) REFERENCES LUNCH_ITEM_AT(CODE_AT)
);
DESCRIBE ORDER_ITEM_AT;

