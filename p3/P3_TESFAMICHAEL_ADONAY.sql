-- Task 5 - Query the data ADONAY TESFAMICHAEL
-- List all students names (in a column named 'Student') in alphabetical order, with the age level (in a column named 'Level'), color and directions of the class and the name of the teacher (in a column named 'Teacher').
SELECT CONCAT_WS(' ',STUDENT_AT.FIRST_NAME_AT, STUDENT_AT.MIDDLE_NAME_AT,STUDENT_AT.LAST_NAME_AT) AS Student,
  CLASS_AT.AGE_LEVEL_AT AS Level,
  CLASS_AT.COLOR_AT AS Color,
  CLASS_AT.DIRECTION_AT AS Direction,
  CONCAT_WS(' ',TEACHER_AT.FIRST_NAME_AT,TEACHER_AT.MIDDLE_NAME_AT,TEACHER_AT.LAST_NAME_AT) AS Teacher
FROM STUDENT_AT
JOIN CLASS_AT ON STUDENT_AT.CLASS_AT_CODE_AT = CLASS_AT.CODE_AT
JOIN ASSIGNMENT_AT ON CLASS_AT.CODE_AT = ASSIGNMENT_AT.CLASS_AT_CODE_AT
JOIN TEACHER_AT ON ASSIGNMENT_AT.TEACHER_AT_ID_AT = TEACHER_AT.ID_AT
ORDER BY Student ASC;
-- For each class level and color show all the student enrolled in alphabetical order per each class (i.e. you start with blue foxes and show all the students enrolled alphabetically, then you go to green foxes, and so on) and their zipcode. Use the following headers for the columns: Color, Level, Student Name, Zipcode
SELECT CLASS_AT.COLOR_AT AS Color,
CLASS_AT.AGE_LEVEL_AT AS Level,
CONCAT_WS(' ',STUDENT_AT.FIRST_NAME_AT, STUDENT_AT.MIDDLE_NAME_AT,STUDENT_AT.LAST_NAME_AT ) AS Student_Name,
STUDENT_AT.ZIPCODE_AT AS Zipcode 
FROM STUDENT_AT 
JOIN CLASS_AT ON STUDENT_AT.CLASS_AT_CODE_AT = CLASS_AT.CODE_AT
ORDER BY Color ASC,
Level ASC, 
Student_Name ASC;
-- For each parent (caretaker) in alphabetical order (show name and work phone), list all the students enrolled (show name, class level and color)
SELECT CONCAT_WS(' ',PARENT_AT.FIRST_NAME_AT, PARENT_AT.MIDDLE_NAME_AT,PARENT_AT.LAST_NAME_AT) AS Parent,
  PARENT_AT.WORK_PHONE_AT AS WorkPhone,
  CONCAT_WS(' ',STUDENT_AT.FIRST_NAME_AT, STUDENT_AT.MIDDLE_NAME_AT, STUDENT_AT.LAST_NAME_AT) AS Student,
  CLASS_AT.AGE_LEVEL_AT AS Level,
  CLASS_AT.COLOR_AT AS Color
FROM PARENT_AT 
JOIN RELATIONSHIP_AT ON PARENT_AT.ID_AT = RELATIONSHIP_AT.PARENT_AT_ID_AT
JOIN STUDENT_AT ON RELATIONSHIP_AT.STUDENT_AT_ID_AT  = STUDENT_AT.ID_AT
JOIN CLASS_AT ON STUDENT_AT.CLASS_AT_CODE_AT  = CLASS_AT.CODE_AT
ORDER BY Parent ASC, Student ASC;
-- For each parent (show name in alphabetical order) list all the teachers (show name in alphabetical order per parent) and their children(students) (show names in alphabetical order per teacher). Use columns headers: parent, teacher, student
SELECT CONCAT_WS(' ',PARENT_AT.FIRST_NAME_AT, PARENT_AT.MIDDLE_NAME_AT, PARENT_AT.LAST_NAME_AT)  AS parent,
  CONCAT_WS(' ',TEACHER_AT.FIRST_NAME_AT, TEACHER_AT.MIDDLE_NAME_AT,TEACHER_AT.LAST_NAME_AT)  AS teacher,
  CONCAT_WS(' ',STUDENT_AT.FIRST_NAME_AT, STUDENT_AT.MIDDLE_NAME_AT, STUDENT_AT.LAST_NAME_AT)  AS student
FROM PARENT_AT 
JOIN RELATIONSHIP_AT ON PARENT_AT.ID_AT = RELATIONSHIP_AT.PARENT_AT_ID_AT
JOIN STUDENT_AT ON RELATIONSHIP_AT.STUDENT_AT_ID_AT = STUDENT_AT.ID_AT
JOIN CLASS_AT ON STUDENT_AT.CLASS_AT_CODE_AT = CLASS_AT.CODE_AT
JOIN ASSIGNMENT_AT ON CLASS_AT.CODE_AT = ASSIGNMENT_AT.CLASS_AT_CODE_AT
JOIN TEACHER_AT ON ASSIGNMENT_AT.TEACHER_AT_ID_AT = TEACHER_AT.ID_AT
ORDER BY parent ASC, teacher ASC, student ASC;

