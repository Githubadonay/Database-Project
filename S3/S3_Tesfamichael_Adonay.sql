-- Task 5 - Query the data by Adonay tesfamichael
-- List alphabetically all the names (with the header name) and the sex of the players (with the header player) for the teams that are enrolled in the "Winter 2019" season (you do not know the ID).
SELECT  TEAM_AT.NAME_AT AS name,
		TEAM_AT.SEX_AT AS player
FROM TEAM_AT 
JOIN REGISTERED_AT  ON TEAM_AT.ID_AT = REGISTERED_AT.TEAM_AT_ID_AT
JOIN DIVISION_AT  ON REGISTERED_AT.DIVISION_AT_ID_AT = DIVISION_AT.ID_AT
JOIN SEASON_AT  ON DIVISION_AT.SEASON_AT_ID_AT = SEASON_AT.ID_AT
WHERE SEASON_AT.SEASON_NAME_AT = 'WINTER'
  AND SEASON_AT.YEAR_AT = 2019
ORDER BY TEAM_AT.NAME_AT;
-- List all the divisions with the season and season ending date (using headers without initials), ordered by season, in which the teams named "Violet" played.
SELECT 
	DIVISION_AT.AGE_AT AS AGE,
    DIVISION_AT.SEX_AT AS PLAYER,
	DIVISION_AT.RANK_AT AS PLACEMENT,
    DIVISION_AT.EMAIL_AT AS EMAIL,
    DIVISION_AT.PHONE_AT AS PHONE,
	CONCAT(SEASON_AT.SEASON_NAME_AT,' ', SEASON_AT.YEAR_AT) AS NAME,
    SEASON_AT.REGISTRATION_END_DATA_AT AS END 
FROM TEAM_AT
JOIN REGISTERED_AT  ON TEAM_AT.ID_AT = REGISTERED_AT.TEAM_AT_ID_AT
JOIN DIVISION_AT  ON REGISTERED_AT.DIVISION_AT_ID_AT = DIVISION_AT.ID_AT
JOIN SEASON_AT  ON DIVISION_AT.SEASON_AT_ID_AT = SEASON_AT.ID_AT
WHERE TEAM_AT.NAME_AT = 'Violet'
ORDER BY SEASON_AT.SEASON_NAME_AT AND SEASON_AT.YEAR_AT;
-- For the club named Lions, list all the teams (names) and their divisions (age, players, rank) in Winter 2019.
SELECT DIVISION_AT.AGE_AT, DIVISION_AT.SEX_AT, DIVISION_AT.RANK_AT
FROM CLUB_AT
JOIN TEAM_AT ON CLUB_AT.ID_AT = TEAM_AT.CLUB_AT_ID_AT
JOIN REGISTERED_AT  ON TEAM_AT.ID_AT = REGISTERED_AT.TEAM_AT_ID_AT
JOIN DIVISION_AT  ON REGISTERED_AT.DIVISION_AT_ID_AT = DIVISION_AT.ID_AT
JOIN SEASON_AT  ON DIVISION_AT.SEASON_AT_ID_AT = SEASON_AT.ID_AT
WHERE CLUB_AT.NAME_AT = 'Lions' 
AND SEASON_AT.SEASON_NAME_AT = 'Winter' 
AND SEASON_AT.YEAR_AT = '2019';

-- For all the divisions in Winter 2019 that are under 10 or younger, list the teams names, clubs names and the year of birth for the players using nice headers.
